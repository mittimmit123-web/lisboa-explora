// Downloads the borders of Lisbon's 24 parishes and writes src/data/parishes.js.
// Run: npm run import-parishes
//
// Like scripts/import-osm.mjs, this runs ONCE and the result is kept in the
// repo, so the app never depends on the OpenStreetMap servers. The map uses
// the borders to colour each neighbourhood (#12 on the to-do list).
//
// Data © OpenStreetMap contributors (ODbL), credited on the map.
// If the main Overpass server is busy, another one can be used, e.g.
//   OVERPASS_URL=https://overpass.private.coffee/api/interpreter npm run import-parishes
import { writeFileSync } from 'node:fs'
import { joinLines } from '../src/lib/osmFilter.js'

const OVERPASS_URL = process.env.OVERPASS_URL ?? 'https://overpass-api.de/api/interpreter'

// Same query as in import-osm.mjs: the parishes inside the city of Lisbon.
const QUERY = `[out:json][timeout:120];
area["name"="Lisboa"]["boundary"="administrative"]["admin_level"="7"]->.city;
rel(area.city)["boundary"="administrative"]["admin_level"="8"];
out geom;`

const wait = (ms) => new Promise((resolve) => setTimeout(resolve, ms))

async function download() {
  for (let attempt = 1; attempt <= 6; attempt++) {
    try {
      const response = await fetch(OVERPASS_URL, {
        method: 'POST',
        headers: { 'User-Agent': 'lisboa-explora-import (student project)' },
        body: new URLSearchParams({ data: QUERY }),
      })
      if (response.ok) return (await response.json()).elements
      console.log(`server busy (${response.status}), attempt ${attempt}/6`)
    } catch (error) {
      console.log(`network error (${error.message}), attempt ${attempt}/6`)
    }
    await wait(attempt * 30_000)
  }
  throw new Error('OpenStreetMap is not reachable, try again later')
}

// 5 decimals = about 1 m. Exact enough for a coloured area, and keeps the
// file small.
const round = (n) => Math.round(n * 1e5) / 1e5

function toParish(relation) {
  const outerLines = relation.members
    .filter((m) => m.type === 'way' && (m.role === 'outer' || m.role === '') && m.geometry)
    .map((m) => m.geometry.map((p) => [round(p.lat), round(p.lon)]))
  return { name: relation.tags.name, polygons: joinLines(outerLines) }
}

console.log('Downloading parish borders ...')
const parishes = (await download()).map(toParish).sort((a, b) => a.name.localeCompare(b.name, 'pt'))
console.log(`${parishes.length} parishes`)

const today = new Date().toISOString().slice(0, 10)
const file = `// GENERATED by scripts/import-parishes.mjs on ${today}. Do not edit by hand.
// The borders of Lisbon's 24 parishes, used to colour the neighbourhoods on
// the map. Loaded only after the map is on screen.
//
// Data © OpenStreetMap contributors (ODbL).
// Fields: name (same as in src/data/neighbourhoods.js), polygons (lists of [lat, lng])
export const PARISHES = [
${parishes.map((p) => '  ' + JSON.stringify(p)).join(',\n')},
]
`
writeFileSync(new URL('../src/data/parishes.js', import.meta.url), file)
console.log('Written: src/data/parishes.js')
