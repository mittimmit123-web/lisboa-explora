// Generates supabase/seed.sql from src/data/spots.js,
// so the app and the database always use the same spots.
// Run: npm run seed
import { writeFileSync } from 'node:fs'
import { SPOTS } from '../src/data/spots.js'

const q = (s) => `'${String(s).replaceAll("'", "''")}'`

const rows = SPOTS.map(
  (s) => `  (${q(s.id)}, ${q(s.name)}, ${q(s.category)}, ${q(s.neighbourhood)}, ${s.lat}, ${s.lng}, ${q(s.rarity)})`,
)

const sql = `-- GENERATED by scripts/make-seed.mjs from src/data/spots.js. Do not edit by hand.
-- Run in Supabase: SQL Editor -> paste -> Run (safe to run again).
insert into public.spots (id, name, category, neighbourhood, lat, lng, rarity) values
${rows.join(',\n')}
on conflict (id) do update set
  name = excluded.name, category = excluded.category, neighbourhood = excluded.neighbourhood,
  lat = excluded.lat, lng = excluded.lng, rarity = excluded.rarity;
`

writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log(`Wrote supabase/seed.sql with ${SPOTS.length} spots`)
